public class dataType {
    public static void main(String[] args) {
        boolean a=true;
        System.out.println(a);
        byte b=4; // 8 bit signed two's complement integer, usefull for saving memory in large arrays
        System.out.println(b);
        short s=56;// 16 bit signed two's complement integer
        System.out.println(s);
        
        // other data types -> int, long, float, double, char
        
    }
}
